#!/usr/bin/env python3
"""Two-position FOG gyro bias calibration (run with the ROS stack stopped; it reads the port directly).

  python3 fog_two_position_cal.py run              interactive: position A, rotate ~180 deg in yaw, position B
  python3 fog_two_position_cal.py capture A|B      capture one position (state kept in --state)
  python3 fog_two_position_cal.py compute          compute from the two captures

The vehicle must be still during each capture. A yaw flip reverses the horizontal Earth rate in the
sensor frame but not the sensor bias, so averaging the two positions cancels it; the vertical Earth
rate is known from latitude and is removed using "up" from the FOG's own accelerometers. The result is
the sensor bias, valid at any heading when used with kvh_node's earth_rate_compensation.

Writes a kvh_node parameter file (--out) with gyro_bias_deg_h and earth_rate_compensation: true.
Redo after the FOG is power cycled.
"""
import argparse, json, math, os, struct, sys, termios, time

EARTH_RATE = 7.2921159e-5            # rad/s
D2H = 180.0 / math.pi * 3600.0       # rad/s -> deg/h
HDR = b"\xfe\x81\xff\x56"


def crc32_mpeg(d):
    c = 0xFFFFFFFF
    for b in d:
        c ^= b << 24
        for _ in range(8):
            c = ((c << 1) ^ 0x04C11DB7) & 0xFFFFFFFF if c & 0x80000000 else (c << 1) & 0xFFFFFFFF
    return c


def capture(port, baud, seconds):
    """Mean gyro (rad/s) and accel (g) in the sensor frame, plus the per-axis gyro std."""
    fd = os.open(port, os.O_RDONLY | os.O_NOCTTY)
    a = termios.tcgetattr(fd)
    a[0] = a[1] = a[3] = 0
    a[2] = termios.CS8 | termios.CREAD | termios.CLOCAL
    a[4] = a[5] = getattr(termios, f"B{baud}")
    a[6][termios.VMIN] = 1
    a[6][termios.VTIME] = 0
    termios.tcsetattr(fd, termios.TCSANOW, a)
    termios.tcflush(fd, termios.TCIFLUSH)
    buf = bytearray()
    g_sum, g_sq, a_sum, n = [0.0] * 3, [0.0] * 3, [0.0] * 3, 0
    t0 = time.time()
    while time.time() - t0 < seconds:
        buf += os.read(fd, 4096)
        while True:
            i = buf.find(HDR)
            if i < 0 or i + 40 > len(buf):
                break
            p = bytes(buf[i:i + 40])
            del buf[:i + 40]
            if crc32_mpeg(p[:36]) != struct.unpack(">I", p[36:])[0] or p[32] != 0x77:
                continue
            g = struct.unpack(">3f", p[4:16])
            acc = struct.unpack(">3f", p[16:28])
            for k in range(3):
                g_sum[k] += g[k]
                g_sq[k] += g[k] * g[k]
                a_sum[k] += acc[k]
            n += 1
    os.close(fd)
    if n == 0:
        sys.exit(f"no valid FOG packets on {port} - is the ROS stack still running?")
    g_mean = [s / n for s in g_sum]
    g_std = [math.sqrt(max(0.0, q / n - m * m)) for q, m in zip(g_sq, g_mean)]
    return {"n": n, "gyro": g_mean, "gyro_std": g_std, "accel": [s / n for s in a_sum]}


def vertical_earth(pos, lat_rad):
    a = pos["accel"]
    norm = math.sqrt(sum(c * c for c in a))
    return [EARTH_RATE * math.sin(lat_rad) * c / norm for c in a]   # specific force points up at rest


def compute(a_pos, b_pos, lat_deg):
    lat = math.radians(lat_deg)
    va, vb = vertical_earth(a_pos, lat), vertical_earth(b_pos, lat)
    ra = [g - v for g, v in zip(a_pos["gyro"], va)]   # bias + horizontal Earth rate, position A
    rb = [g - v for g, v in zip(b_pos["gyro"], vb)]
    bias = [(x + y) / 2 for x, y in zip(ra, rb)]
    # The horizontal Earth rate turns by the yaw rotation, so |ra - rb| / 2 = h * sin(rotation / 2).
    half_diff = math.sqrt(sum((x - y) ** 2 for x, y in zip(ra, rb))) / 2
    h = EARTH_RATE * math.cos(lat)
    return {
        "bias_deg_h": [b * D2H for b in bias],
        "earth_horizontal_deg_h": half_diff * D2H,
        "expected_horizontal_deg_h": h * D2H,
        "rotation_deg": math.degrees(2 * math.asin(min(1.0, half_diff / h))),
    }


def report_and_write(res, args):
    b = res["bias_deg_h"]
    print(f"\nFOG sensor bias (deg/h): {b[0]:+.3f} {b[1]:+.3f} {b[2]:+.3f}")
    print(f"check: half the A-B difference {res['earth_horizontal_deg_h']:.2f} deg/h "
          f"(= horizontal Earth rate {res['expected_horizontal_deg_h']:.2f} at exactly 180 deg) "
          f"-> rotation between positions ~{res['rotation_deg']:.0f} deg")
    # Rotation off by d degrees leaves ~11.45*sin(d/2) deg/h on the roll/pitch axes only; heading is unaffected.
    if res["rotation_deg"] < 150:
        print("WARNING: positions are less than 150 deg apart; rotate closer to 180 deg and redo.")
    with open(args.out, "w") as f:
        f.write("# Generated by fog_two_position_cal.py on %s. Redo after the FOG is power cycled.\n" % time.strftime("%Y-%m-%d %H:%M"))
        f.write("kvh_node:\n  ros__parameters:\n")
        f.write(f"    gyro_bias_deg_h: [{b[0]:.4f}, {b[1]:.4f}, {b[2]:.4f}]\n")
        f.write("    earth_rate_compensation: true\n")
        f.write(f"    latitude_deg: {args.latitude}\n")
    print(f"wrote {args.out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mode", choices=["run", "capture", "compute"])
    ap.add_argument("position", nargs="?", choices=["A", "B"])
    ap.add_argument("--port", default="/dev/ttyTHS1")
    ap.add_argument("--baud", type=int, default=460800)
    ap.add_argument("--seconds", type=float, default=60.0)
    ap.add_argument("--latitude", type=float, default=40.44)
    ap.add_argument("--state", default="/tmp/fog_cal_state.json")
    ap.add_argument("--out", default="fog_bias.yaml")
    args = ap.parse_args()

    if args.mode == "capture":
        if not args.position:
            sys.exit("capture needs A or B")
        state = json.load(open(args.state)) if os.path.exists(args.state) else {}
        print(f"capturing position {args.position} for {args.seconds:.0f} s - keep the vehicle still")
        state[args.position] = capture(args.port, args.baud, args.seconds)
        json.dump(state, open(args.state, "w"))
        p = state[args.position]
        print(f"  {p['n']} packets, max gyro std {max(p['gyro_std']) * 180 / math.pi:.4f} deg/s")
        return
    if args.mode == "compute":
        state = json.load(open(args.state))
        report_and_write(compute(state["A"], state["B"], args.latitude), args)
        return
    input("Position A: vehicle still, press Enter to start...")
    a_pos = capture(args.port, args.baud, args.seconds)
    input("Rotate the vehicle ~180 deg in yaw, keep it still, press Enter...")
    b_pos = capture(args.port, args.baud, args.seconds)
    report_and_write(compute(a_pos, b_pos, args.latitude), args)


if __name__ == "__main__":
    main()
